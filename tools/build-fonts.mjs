// Embeds the Hebrew + Latin font subsets used by the summary PDF renderer
// into app/js/fonts.js as data URIs (the PDF is drawn from an SVG image,
// which cannot load external fonts).
// Fonts: Assistant and Frank Ruhl Libre, SIL Open Font License 1.1 (Google Fonts).
import { readFileSync, writeFileSync } from 'node:fs';
const dir = new URL('./fonts/', import.meta.url);
const b64 = (f) => readFileSync(new URL(f, dir)).toString('base64');
const HE = 'U+0307-0308, U+0590-05FF, U+200C-2010, U+20AA, U+25CC, U+FB1D-FB4F';
const LA = 'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD';
const face = (family, weight, file, range) =>
  `@font-face{font-family:'${family}';font-style:normal;font-weight:${weight};src:url(data:font/woff2;base64,${b64(file)}) format('woff2');unicode-range:${range};}`;
const css = [
  face('PdfSans', '200 800', 'asst-he.woff2', HE),
  face('PdfSans', '200 800', 'asst-la.woff2', LA),
  face('PdfSerif', '700', 'frl-he.woff2', HE),
  face('PdfSerif', '700', 'frl-la.woff2', LA),
].join('\n');
const out = `/* Generated by tools/build-fonts.mjs. Fonts: Assistant, Frank Ruhl Libre (SIL OFL 1.1). */
(function (root) { root.ShipoFonts = { css: ${JSON.stringify(css)} }; })(typeof self !== 'undefined' ? self : globalThis);
`;
writeFileSync(new URL('../app/js/fonts.js', import.meta.url), out);
console.log('fonts.js', out.length, 'bytes');
